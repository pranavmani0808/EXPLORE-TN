export function addKodaiPoi(poi: KodaiPoiRecord): KodaiPoiRecord {
  const pois = getAllKodaiPois();
  pois.unshift(poi);
  saveAllKodaiPois(pois);
  return poi;
}

export function updateKodaiPoi(poiId: string, updated: Partial<KodaiPoiRecord>): KodaiPoiRecord | undefined {
  const pois = getAllKodaiPois();
  const index = pois.findIndex((p) => p.id === poiId || p.slug === poiId);
  if (index !== -1) {
    pois[index] = { ...pois[index], ...updated, lastVerified: "Just now" };
    saveAllKodaiPois(pois);
    return pois[index];
  }
  return undefined;
}

export function deleteKodaiPoi(poiId: string): boolean {
  const pois = getAllKodaiPois();
  const filtered = pois.filter((p) => p.id !== poiId && p.slug !== poiId);
  if (filtered.length !== pois.length) {
    saveAllKodaiPois(filtered);
    return true;
  }
  return false;
}
