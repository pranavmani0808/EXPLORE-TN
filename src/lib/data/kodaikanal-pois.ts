const KODAI_POIS_STORAGE_KEY = "etn_kodai_pois_v3";

export function getAllKodaiPois(): KodaiPoiRecord[] {
  if (typeof window === "undefined") return INITIAL_KODAI_POIS;
  try {
    const raw = localStorage.getItem(KODAI_POIS_STORAGE_KEY);
    if (raw) {
      const parsed: KodaiPoiRecord[] = JSON.parse(raw);
      if (parsed && parsed.length > 0) return parsed;
    }
  } catch {}
  return INITIAL_KODAI_POIS;
}

export function saveAllKodaiPois(pois: KodaiPoiRecord[]): void {
  if (typeof window === "undefined") return;
  try {
    localStorage.setItem(KODAI_POIS_STORAGE_KEY, JSON.stringify(pois));
    window.dispatchEvent(new CustomEvent("etn_kodai_pois_updated", { detail: pois }));
  } catch {}
}

export function getKodaiPoiBySlug(slug: string): KodaiPoiRecord | undefined {
  const norm = slug.toLowerCase().trim();
  const pois = getAllKodaiPois();
  return pois.find((p) => p.slug.toLowerCase() === norm || p.id.toLowerCase() === norm);
}

export function getKodaiPoisByCategory(category: KodaiPoiCategory | "all"): KodaiPoiRecord[] {
  const pois = getAllKodaiPois();
  if (category === "all") return pois;
  return pois.filter((p) => p.category === category);
}

